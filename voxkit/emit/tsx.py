"""TSX emission: a thin template over the program, with no arithmetic in it.

Every number that reaches the renderer is already decided in
`emit/choreography.py`. The emitter formats literals and nothing else. That is
deliberate: when the generator did its own maths, a defect in the maths and a
defect in the template produced the same TSX, and the only way to tell them apart
was to render and watch. Now the program can be printed, asserted on and gated,
and the TSX cannot disagree with it because it has nothing to compute.

`Film.tsx` and `Root.tsx` are generated too. They used to be hand-edited maps,
and a module that passed every gate but was missing from `BUILT` rendered as a
placeholder in the finished film without a word of complaint. A film's module
list is derivable from the plans, so it is derived.
"""
from __future__ import annotations

from pathlib import Path

from .choreography import CardMotion, Khat, MarkMotion, ModuleProgram, ShotProgram

STAGE_W, STAGE_H = 1920, 1080

HEADER = """\
// Generated by voxkit. Do not edit: change the plan, then `vox emit <module>`.
import React from "react";
import {AbsoluteFill, Audio, Sequence, staticFile} from "remotion";
import {
  CamKey,
  CardKind,
  Element,
  ElementFrom,
  ElementPose,
  Khat,
  Marker,
  MarkerMotion,
  MarkerShape,
  PaperStage,
  PenName,
  STAGE_H,
  STAGE_W,
} from "../components";

const HandMark: React.FC<{
  shape: MarkerShape;
  box: [number, number, number, number];
  at: number;
  pen?: PenName;
  color?: string;
  duration?: number;
  rotate?: number;
  motion?: MarkerMotion;
  sw?: number;
  seed?: number;
  /**
   * The layer this mark belongs to. A mark is drawn ON one card, so it sits just
   * above that card and *below* anything pasted over it.
   *
   * Without this every mark was drawn above the whole collage. A circle around a
   * dictionary whose corner is covered by a label was painted across the label,
   * so the gesture appeared to point at two things at once — the client's "the
   * arrow misses the word", in its most literal form. The mark was in the right
   * place; it was in the wrong layer.
   */
  z?: number;
}> = ({shape, box, at, pen = "marker", color = "coral", duration = 14, rotate = 0,
     motion = "draw", sw, seed = 101, z = 1}) => {
  const [x0, y0, x1, y1] = box;
  return (
    <div style={{position: "absolute", left: `${x0 * 100}%`, top: `${y0 * 100}%`,
                 width: `${(x1 - x0) * 100}%`, height: `${(y1 - y0) * 100}%`,
                 zIndex: z * 10 + 5}}>
      <Marker shape={shape} pen={pen} color={color} at={at} duration={duration}
              rotate={rotate} motion={motion} strokeWidth={sw}
              width={(x1 - x0) * STAGE_W} height={(y1 - y0) * STAGE_H} seed={seed} />
    </div>
  );
};

const Card: React.FC<{
  src: string;
  x: number;
  y: number;
  w: number;
  aspect: number;
  enterFrame: number;
  travel: number;
  from: ElementFrom;
  phase: number;
  stepped: number;
  kind: CardKind;
  poses?: ElementPose[];
  z?: number;
}> = ({src, x, y, w, aspect, enterFrame, travel, from, phase, stepped, kind, poses, z = 1}) => (
  <div style={{position: "absolute", inset: 0, zIndex: z * 10}}>
    <Element src={src} at={[x, y]} width={w * STAGE_W} aspect={aspect}
             enterFrame={enterFrame} travel={travel} from={from} outline={0}
             phase={phase} stepped={stepped} rotate={0} poses={poses} kind={kind} />
  </div>
);
"""


def num(v: float, places: int = 4) -> str:
    """A stable literal. Trailing zeros are trimmed so a regenerated file is
    byte-identical when nothing changed — which is what makes a diff readable."""
    s = f"{v:.{places}f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def _camera(shot: ShotProgram) -> str:
    keys = ",\n          ".join(
        f'{{at: {k.at}, x: {num(k.x)}, y: {num(k.y)}, zoom: {num(k.zoom)}, ease: "{k.ease}"}}'
        for k in shot.camera
    )
    return f"[\n          {keys},\n        ]"


def _mark(m: MarkMotion, cards: tuple[CardMotion, ...], indent: str) -> list[str]:
    box = f"[{num(m.box.x0)}, {num(m.box.y0)}, {num(m.box.x1)}, {num(m.box.y1)}]"
    lines = [
        f'{indent}<HandMark',
        f'{indent}  shape="{m.shape}"',
        f"{indent}  box={{{box}}}",
        f"{indent}  at={{{m.at}}}",
        f"{indent}  duration={{{m.duration}}}",
        f"{indent}  rotate={{{num(m.rotate, 2)}}}",
        f'{indent}  pen="{m.pen}"',
        f'{indent}  motion="{m.motion}"',
    ]
    if m.sw:
        lines.append(f"{indent}  sw={{{int(m.sw)}}}")
    if m.on:
        # Drawn on a card, so drawn in that card's layer — above the card itself,
        # below anything pasted over it.
        z = next((c.z for c in cards if c.name == m.on), 1)
        lines.append(f"{indent}  z={{{z}}}")
    lines += [f'{indent}  color="{m.color}"', f"{indent}  seed={{{m.seed}}}", f"{indent}/>"]
    return lines


def _khat(k: Khat, indent: str) -> list[str]:
    return [
        f"{indent}<Khat",
        f'{indent}  text="{k.text}"',
        f"{indent}  at={{{k.at}}}",
        f"{indent}  duration={{{k.duration}}}",
        f"{indent}  x={{{num(k.x)}}}",
        f"{indent}  y={{{num(k.y)}}}",
        f"{indent}  w={{{num(k.w)}}}",
        f"{indent}  h={{{num(k.h)}}}",
        f"{indent}  sw={{{k.sw}}}",
        f'{indent}  color="{k.color}"',
        f"{indent}  rotate={{{num(k.rotate, 2)}}}",
        f"{indent}  seed={{{k.seed}}}",
        f"{indent}  z={{{k.z}}}",
        f"{indent}/>",
    ]


def render_shot(shot: ShotProgram, index: int) -> list[str]:
    name = f"S{index:02d}"
    out = [f"const {name}: React.FC = () => (", f'  <PaperStage camera={{{_camera(shot)}}}',
           f'             plate="{shot.plate}" totalFrames={{{shot.span}}}',
           f"             phase={{{num(round(index * 0.45, 2), 2)}}}>", "    <AbsoluteFill>"]

    for card in shot.cards:
        pose_prop = ""
        if card.poses:
            poses = ", ".join(f'{{atFrame: {p.at}, src: "{p.src}"}}' for p in card.poses)
            pose_prop = f" poses={{[{poses}]}}"
        out.append(
            f'      <Card src="{card.src}" x={{{num(card.rect.cx)}}} y={{{num(card.rect.cy)}}} '
            f"w={{{num(card.rect.w)}}} aspect={{{num(card.rect.h / card.rect.w if card.rect.w else 0.7)}}} "
            f'enterFrame={{{card.enter}}} travel={{{card.travel}}} from="{card.from_side}" '
            f"phase={{{num(card.phase, 2)}}} stepped={{{card.stepped}}} "
            f'kind="{card.kind}" z={{{card.z}}}{pose_prop} />'
        )

    for m in shot.marks:
        out += _mark(m, shot.cards, "      ")
    for k in shot.khats:
        out += _khat(k, "      ")

    out += ["    </AbsoluteFill>", "  </PaperStage>", ");", ""]
    return out


def render_module(prog: ModuleProgram) -> str:
    lines = [HEADER, ""]
    for i, shot in enumerate(prog.shots, 1):
        lines += render_shot(shot, i)

    upper = prog.module.upper()
    lines += [f"export const {upper}: React.FC = () => {{",
              "  const shots: {at: number; dur: number; C: React.FC}[] = ["]
    for i, shot in enumerate(prog.shots, 1):
        lines.append(f"    {{at: {shot.start}, dur: {shot.span}, C: S{i:02d}}},")
    lines += [
        "  ];",
        "  return (",
        f'    <AbsoluteFill style={{{{background: "#EFE7D6"}}}}>',
        f'      <Audio src={{staticFile("audio/{prog.module}.wav")}} />',
        "      {shots.map(({at, dur, C}, i) => (",
        f'        <Sequence key={{i}} from={{at}} durationInFrames={{dur}} '
        f'name={{`{prog.module}-s${{i + 1}}`}}>',
        "          <C />",
        "        </Sequence>",
        "      ))}",
        "    </AbsoluteFill>",
        "  );",
        "};",
        "",
    ]
    return "\n".join(lines)


def render_film(modules: list[tuple[str, int]], background: str = "#EFE7D6") -> str:
    """The whole film, derived from the plans.

    A film's module list is not a thing to remember. Hand-maintained, a module
    that passed every gate and was missing from this map rendered as a
    placeholder in the finished film, and nothing objected.
    """
    lines = [
        "// Generated by voxkit. Do not edit: the module list comes from the plans.",
        'import React from "react";',
        'import {AbsoluteFill, Sequence} from "remotion";',
        "",
    ]
    for mod, _ in modules:
        lines.append(f'import {{{mod.upper()}}} from "../shots/{mod.upper()}";')
    lines += ["", "const BUILT: Record<string, React.FC> = {"]
    for mod, _ in modules:
        lines.append(f"  {mod}: {mod.upper()},")
    lines += [
        "};",
        "",
        "export const FILM: {id: string; dur: number}[] = [",
    ]
    for mod, frames in modules:
        lines.append(f'  {{id: "{mod}", dur: {frames}}},')
    lines += [
        "];",
        "",
        "export const Film: React.FC = () => {",
        "  let at = 0;",
        "  const rows = FILM.map((row) => {",
        "    const from = at;",
        "    at += row.dur;",
        "    return {...row, from};",
        "  });",
        "  return (",
        f'    <AbsoluteFill style={{{{background: "{background}"}}}}>',
        "      {rows.map(({id, from, dur}) => {",
        "        const Shot = BUILT[id];",
        "        if (!Shot) return null;",
        "        return (",
        "          <Sequence key={id} from={from} durationInFrames={dur} name={id}>",
        "            <Shot />",
        "          </Sequence>",
        "        );",
        "      })}",
        "    </AbsoluteFill>",
        "  );",
        "};",
        "",
    ]
    return "\n".join(lines)


def render_root(modules: list[tuple[str, int]], fps: int = 30,
                width: int = STAGE_W, height: int = STAGE_H) -> str:
    lines = [
        "// Generated by voxkit. Do not edit: the compositions come from the plans.",
        'import React from "react";',
        'import {Composition} from "remotion";',
    ]
    for mod, _ in modules:
        lines.append(f'import {{{mod.upper()}}} from "./shots/{mod.upper()}";')
    lines += ['import {Film} from "./film/Film";', "", "export const RemotionRoot: React.FC = () => {",
              "  return (", "    <>"]
    for mod, frames in modules:
        lines.append(f'      <Composition id="{mod.upper()}" component={{{mod.upper()}}} '
                     f"durationInFrames={{{frames}}} fps={{{fps}}} "
                     f"width={{{width}}} height={{{height}}} />")
    lines += [
        "      <Composition id=\"FILM\" component={Film} "
        f"durationInFrames={{{sum(f for _, f in modules)}}} fps={{{fps}}} "
        f"width={{{width}}} height={{{height}}} />",
        "    </>",
        "  );",
        "};",
        "",
    ]
    return "\n".join(lines)


def write(prog: ModuleProgram, remotion: Path) -> Path:
    """Write the shot file and the two generated indexes."""
    shots = remotion / "src" / "shots"
    shots.mkdir(parents=True, exist_ok=True)
    path = shots / f"{prog.module.upper()}.tsx"
    path.write_text(render_module(prog), encoding="utf-8")
    return path


def write_indexes(modules: list[tuple[str, int]], remotion: Path, *,
                  fps: int = 30, width: int = STAGE_W, height: int = STAGE_H,
                  background: str = "#EFE7D6") -> list[Path]:
    film = remotion / "src" / "film" / "Film.tsx"
    root = remotion / "src" / "Root.tsx"
    film.parent.mkdir(parents=True, exist_ok=True)
    film.write_text(render_film(modules, background), encoding="utf-8")
    root.write_text(render_root(modules, fps, width, height), encoding="utf-8")
    return [film, root]
